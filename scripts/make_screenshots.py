"""生成 README 用的终端截图（SVG）和徽章，全部是 --demo 合成数据，可重复运行。

用法（仓库根目录）：
    .venv/bin/python scripts/make_screenshots.py

每张截图都是 rich 的 Console(record=True) 导出的 SVG：在临时 HOME 里从头跑一遍 demo 流程，
所以路径显示成 ~/.config/mcd-git/demo，不会出现本机用户名、真实门店、订单或 Token。
吃麦贡献图 assets/card-demo.svg（天际线）、card-receipt-demo.svg（小票）、card-grid-demo.svg（平面格子）也由它生成：
另开一个全新的 demo 世界，在临时 HOME 里用默认文件名跑 card（截图显示「已写入 ~/mcd-contributions.svg」，
不露本机路径），写完再拷进 assets/（和 tests/test_card.py、tests/test_card_styles.py 的快照条件一致）。
"""
from __future__ import annotations

import html
import io
import os
import re
import shlex
import shutil
import sys
import tempfile
from pathlib import Path
from typing import List, Optional

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))  # 没 pip install 也能跑

from rich.cells import cell_len  # noqa: E402
from rich.console import Console  # noqa: E402
from rich.terminal_theme import TerminalTheme  # noqa: E402
from rich.text import Text  # noqa: E402

from mcd_git.cli import main  # noqa: E402

ASSETS = ROOT / "assets"
WIDTH = 96
TITLE = "git mcd · demo（合成数据）"

# 接近 GitHub Dark 的配色
THEME = TerminalTheme(
    (13, 17, 23),
    (201, 209, 217),
    [(72, 79, 88), (255, 123, 114), (63, 185, 80), (210, 153, 34), (88, 166, 255), (188, 140, 255), (57, 197, 207), (177, 186, 196)],
    [(110, 118, 129), (255, 161, 152), (86, 211, 100), (227, 179, 65), (121, 192, 255), (210, 168, 255), (86, 212, 221), (240, 246, 252)],
)

# (文件名, 一条或几条命令, 交互时自动回答的内容)；按顺序在同一个 demo 状态里执行
STEPS = [
    ("help", ["help"], None),
    ("init", ["init --city 示例市 --keyword 码农路", "init --pick 1"], None),
    ("status", ["status"], None),
    ("add", ["add 巨无霸 中薯条 中可乐 --no-pickle"], None),
    ("diff", ["diff"], None),
    ("rebase", ["rebase"], None),
    ("commit", ["commit -m 发版前的午饭"], None),
    ("push", ["push --at 12:20 --locker --no-tableware"], "y"),
    ("log-graph", ["log --graph"], None),
    ("show", ["show"], None),
    ("cherry-pick", ["cherry-pick HEAD"], None),
    ("pull", ["pull"], "y"),
    ("log-stat", ["log --stat -n 3"], None),
]


def shot(name: str, commands: List[str], answer: Optional[str]) -> None:
    console = Console(file=io.StringIO(), record=True, width=WIDTH, force_terminal=True, color_system="truecolor", highlight=False, markup=False, emoji=False)

    def ask(prompt: str) -> str:
        console.print(Text.assemble(prompt, (answer or "", "bold")))
        return answer or ""

    for command in commands:
        console.print(Text.assemble(("$ ", "bold green"), ("git mcd " + command, "bold")))
        code = main(["--demo"] + shlex.split(command), console=console, interactive=answer is not None, input_fn=ask)
        if code != 0:
            raise SystemExit(f"{name}: git mcd {command} 退出码 {code}")
    path = ASSETS / f"{name}.svg"
    svg = console.export_svg(title=TITLE, theme=THEME)
    path.write_text(postprocess(svg), encoding="utf-8")
    print(f"wrote {path.relative_to(ROOT)}")


_TEXT_RE = re.compile(r'(<text\b[^>]*?\btextLength=")([0-9.]+)("[^>]*>)([^<]*)(</text>)')
_FONT_FACE_RE = re.compile(r"\s*@font-face\s*\{[^}]*\}")
_MONO = 'font-family: "SFMono-Regular", Menlo, Consolas, "Liberation Mono", "Noto Sans Mono CJK SC", monospace;'


def postprocess(svg: str) -> str:
    """rich 导出 SVG 的两处修正：
    1. textLength 按 len(text) 算，中文（占两格）会被压扁 → 按显示宽度重算；
    2. 去掉从 CDN 拉字体的 @font-face 和带外链的注释，图片里不留任何外部地址（只剩 demo 用的 example.com）。
    """

    def fix(match: "re.Match[str]") -> str:
        content = html.unescape(match.group(4))
        if not content:
            return match.group(0)
        per_char = float(match.group(2)) / len(content)
        return f"{match.group(1)}{per_char * cell_len(content):.1f}{match.group(3)}{match.group(4)}{match.group(5)}"

    svg = _TEXT_RE.sub(fix, svg)
    svg = _FONT_FACE_RE.sub("", svg)
    svg = svg.replace("font-family: Fira Code, monospace;", _MONO)
    svg = re.sub(r"<!-- Generated with Rich[^>]*-->", "<!-- generated by scripts/make_screenshots.py (rich) -->", svg)
    return svg


BADGE = (
    '<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="20" role="img" aria-label="{label}: {value}">'
    '<linearGradient id="s" x2="0" y2="100%"><stop offset="0" stop-color="#bbb" stop-opacity=".1"/><stop offset="1" stop-opacity=".1"/></linearGradient>'
    '<clipPath id="r"><rect width="{w}" height="20" rx="3" fill="#fff"/></clipPath>'
    '<g clip-path="url(#r)"><rect width="{lw}" height="20" fill="#555"/><rect x="{lw}" width="{vw}" height="20" fill="{color}"/>'
    '<rect width="{w}" height="20" fill="url(#s)"/></g>'
    '<g fill="#fff" text-anchor="middle" font-family="Verdana,Geneva,DejaVu Sans,PingFang SC,Microsoft YaHei,sans-serif" font-size="11">'
    '<text x="{lx}" y="14">{label}</text><text x="{vx}" y="14">{value}</text></g></svg>\n'
)

BADGES = [
    ("python", "python", "3.9+", "#3776ab"),
    ("license", "license", "MIT", "#2ea043"),
    ("mcp", "MCP", "streamable http", "#8250df"),
    ("demo", "try", "--demo 无需 Token", "#d29922"),
    ("unofficial", "非官方", "参赛作品", "#6e7681"),
]


def _text_width(text: str) -> int:
    return sum(12 if ord(ch) > 0x2E80 else 7 for ch in text) + 10


def badges() -> None:
    folder = ASSETS / "badges"
    folder.mkdir(parents=True, exist_ok=True)
    for name, label, value, color in BADGES:
        lw, vw = _text_width(label), _text_width(value)
        svg = BADGE.format(w=lw + vw, lw=lw, vw=vw, lx=lw / 2, vx=lw + vw / 2, label=label, value=value, color=color)
        (folder / f"{name}.svg").write_text(svg, encoding="utf-8")
        print(f"wrote {(folder / name).relative_to(ROOT)}.svg")


def _fresh_home(home: str) -> None:
    os.environ["HOME"] = home
    for key in ("MCD_GIT_HOME", "MCD_GIT_NOW", "MCD_MCP_TOKEN", "COLUMNS"):
        os.environ.pop(key, None)


def _copy_card(source: Path, name: str) -> None:
    shutil.copyfile(source, ASSETS / name)
    print(f"wrote assets/{name}")


def run() -> None:
    ASSETS.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory() as home:
        _fresh_home(home)
        for step in STEPS:
            shot(*step)
    # 贡献图在全新的 demo 世界里单独生成（当天没有 push 过）：天际线 → assets/card-demo.svg，
    # 小票 → assets/card-receipt-demo.svg，平面格子 → assets/card-grid-demo.svg（格子版只要卡片，不要终端截图）
    # 在临时 HOME 里用默认文件名写，截图显示「已写入 ~/mcd-contributions.svg」，不露本机路径；写完再拷进 assets/。
    # 天际线和格子默认都写 mcd-contributions.svg，所以格子要等天际线拷走之后再生成。
    cwd = os.getcwd()
    with tempfile.TemporaryDirectory() as tmp:
        home = os.path.realpath(tmp)  # macOS 的临时目录经 /private 符号链接，HOME 和 cwd 要同口径才显示成 ~
        _fresh_home(home)
        os.chdir(home)
        try:
            shot("card", ["card"], None)
            _copy_card(Path(home) / "mcd-contributions.svg", "card-demo.svg")
            shot("card-receipt", ["card --style receipt"], None)
            _copy_card(Path(home) / "mcd-receipt.svg", "card-receipt-demo.svg")
            quiet = Console(file=io.StringIO(), width=WIDTH)
            if main(["--demo", "card", "--style", "grid"], console=quiet, interactive=False) != 0:
                raise SystemExit("card --style grid 失败")
            _copy_card(Path(home) / "mcd-contributions.svg", "card-grid-demo.svg")
        finally:
            os.chdir(cwd)
    badges()


if __name__ == "__main__":
    run()
